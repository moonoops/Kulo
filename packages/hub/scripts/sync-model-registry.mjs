import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const MODELS_DEV_URL = "https://models.dev/api.json";
const LITELLM_URL = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const parserDistPath = path.resolve(scriptDir, "../dist/model-metadata-parser.js");
const snapshotOutPath = path.resolve(scriptDir, "../src/model-metadata-snapshot.ts");

async function fetchJson(url) {
  const res = await fetch(url, {
    headers: { Accept: "application/json", "Cache-Control": "no-cache" },
    signal: AbortSignal.timeout(20_000),
  });
  if (!res.ok) throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
  return res.json();
}

const { buildNormalizedCatalog } = await import(pathToFileURL(parserDistPath).href);

const [modelsDevRaw, liteLLMRaw] = await Promise.all([
  fetchJson(MODELS_DEV_URL),
  fetchJson(LITELLM_URL).catch((err) => {
    console.warn("Warning: LiteLLM fetch failed, continuing with models.dev only:", err.message);
    return undefined;
  }),
]);

const catalog = buildNormalizedCatalog(modelsDevRaw, liteLLMRaw, Date.now());
const serialized = JSON.stringify(catalog);
const providerCount = Object.keys(catalog.providers).length;
const providerModels = Object.values(catalog.providers).reduce((sum, bucket) => sum + Object.keys(bucket).length, 0);
const canonicalModels = Object.keys(catalog.models).length;

const fileSource = `/**
 * Auto-generated by \`node packages/hub/scripts/sync-model-registry.mjs\`.
 * Slim offline factory snapshot derived from \`models.dev/api.json\` and LiteLLM capability metadata.
 * Do not edit by hand; re-run the sync script before releases.
 */
export const BUNDLED_MODEL_METADATA_SNAPSHOT_JSON = ${JSON.stringify(serialized)};
`;

await fs.writeFile(snapshotOutPath, fileSource, "utf8");
console.log(
  `Synced model metadata snapshot: ${providerCount} providers, ${providerModels} provider entries, ${canonicalModels} canonical models, ${(Buffer.byteLength(serialized, "utf8") / 1024).toFixed(1)} KB JSON`,
);
